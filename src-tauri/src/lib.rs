//! Tauri layer: exposes the core (`eloria-core`) to the interface through commands.
//! No business logic here; everything goes through `Workspace`.

mod commands;
mod watcher;

use std::path::PathBuf;
use std::sync::atomic::AtomicBool;
use std::sync::{Arc, Mutex};

use eloria_core::settings::Settings;
use eloria_core::Workspace;
use tauri::Manager;

pub struct AppState {
    pub ws: Arc<Mutex<Option<Workspace>>>,
    pub settings: Mutex<Settings>,
    pub settings_path: PathBuf,
    pub watcher: Mutex<Option<notify::RecommendedWatcher>>,
    /// Set to `true` to stop the current AI generation.
    pub ai_cancel: Arc<AtomicBool>,
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
